import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {readCapabilities, readNameAndOilFeatures, requireRuntimeCapabilities,
  requireNameAndOilAgreement} from '../web/content/community-runtime-registry.mjs';

const fixture = JSON.parse(readFileSync(new URL('./fixtures/community-mod-manager/alchemist-names-oils.json', import.meta.url)));
const cp = Uint8Array.from(Buffer.from(fixture.mmcpHex, 'hex'));
const fr = Uint8Array.from(Buffer.from(fixture.mmfrHex, 'hex'));
const changed = (bytes, offset, value) => {
  const copy = bytes.slice();
  new DataView(copy.buffer).setUint32(offset, value, true);
  return copy;
};

test('reads bytes generated by the pinned community encoder, including buffer slices', () => {
  for (const [bytes, digest] of [[cp, fixture.mmcpSha256], [fr, fixture.mmfrSha256]])
    assert.equal(createHash('sha256').update(bytes).digest('hex'), digest);
  const padded = new Uint8Array(fr.length + 12);
  padded.set(fr, 7);
  const features = readNameAndOilFeatures(padded.subarray(7, 7 + fr.length));
  assert.deepEqual(features.names, [{id: 'NM18', tables: ['HN69', 'HN70', 'HN71', 'HN72']}]);
  assert.deepEqual(features.oils, [
    {id: 'ALo1', text: 'Paralytic Oil - brief stun on weapon hit'},
    {id: 'ALo2', text: 'Transmutation Oil - +5 gold on weapon hit'},
  ]);
  assert.deepEqual(readCapabilities(cp), ['stock.ap78-enchantment-row.v1', 'stock.name-generator.v1']);
  requireNameAndOilAgreement(readCapabilities(cp), features);
});

test('truncation at every byte boundary and trailing data are refused', () => {
  for (const [bytes, parse] of [[cp, readCapabilities], [fr, readNameAndOilFeatures]]) {
    for (let i = 0; i < bytes.length; i++) assert.throws(() => parse(bytes.subarray(0, i)));
    assert.throws(() => parse(new Uint8Array([...bytes, 0])), /trailing/);
    assert.throws(() => parse(changed(bytes, 0, 0)), /magic/);
    assert.throws(() => parse(changed(bytes, 4, 9)), /schema/);
  }
});

test('huge counts, malformed names, duplicate/out-of-order capabilities are refused', () => {
  assert.throws(() => readCapabilities(changed(cp, 8, 0xffffffff)), /count/);
  assert.throws(() => readCapabilities(changed(cp, 12, 0xffffffff)), /length/);
  const invalid = cp.slice(); invalid[16] = 255;
  assert.throws(() => readCapabilities(invalid), /name/);
  const newline = new Uint8Array([...cp, 10]);
  const lastLengthOffset = 16 + new DataView(cp.buffer).getUint32(12, true);
  new DataView(newline.buffer).setUint32(lastLengthOffset,
    new DataView(cp.buffer).getUint32(lastLengthOffset, true) + 1, true);
  assert.throws(() => readCapabilities(newline), /name/);
  const header = cp.slice(0, 12);
  const firstLength = new DataView(cp.buffer).getUint32(12, true);
  const first = cp.slice(12, 16 + firstLength), second = cp.slice(16 + firstLength);
  assert.throws(() => readCapabilities(new Uint8Array([...header, ...first, ...first])), /increasing/);
  assert.throws(() => readCapabilities(new Uint8Array([...header, ...second, ...first])), /increasing/);
});

test('private name tables cannot collide with stock names or duplicate one another', () => {
  const fourCC = id => Buffer.from(id).readUInt32LE();
  assert.throws(() => readNameAndOilFeatures(changed(fr, 16, fourCC('NM17'))), /stock/);
  assert.throws(() => readNameAndOilFeatures(changed(fr, 20, fourCC('HN68'))), /stock/);
  assert.throws(() => readNameAndOilFeatures(changed(fr, 24, fourCC('HN69'))), /duplicate/);
  assert.throws(() => readNameAndOilFeatures(changed(fr, 20, fourCC('AP69'))), /HN/);
  assert.throws(() => readNameAndOilFeatures(changed(fr, 8, 257)), /count/);
  assert.throws(() => readNameAndOilFeatures(changed(fr, 12, 1025)), /count/);
});

test('oil text rejects undefined Windows-1252 bytes and NUL, preserving valid extended text', () => {
  for (const char of [0, 0x81, 0x8d, 0x8f, 0x90, 0x9d]) {
    const invalid = fr.slice(); invalid[44] = char;
    assert.throws(() => readNameAndOilFeatures(invalid), /Windows-1252/);
  }
  const extended = fr.slice(); extended[44] = 0x80;
  assert.equal(readNameAndOilFeatures(extended).oils[0].text[0], '€');
  assert.throws(() => readNameAndOilFeatures(changed(fr, 40, 513)), /length/);
});

test('valid registries do not bypass missing runtime hooks or mismatched feature selection', () => {
  const capabilities = readCapabilities(cp), features = readNameAndOilFeatures(fr);
  assert.throws(() => requireRuntimeCapabilities(capabilities, new Set()), /lacks required/);
  requireRuntimeCapabilities(capabilities, new Set(capabilities));
  assert.throws(() => requireNameAndOilAgreement([], features), /mismatch/);
  assert.throws(() => requireNameAndOilAgreement(capabilities, {names: [], oils: features.oils}), /mismatch/);
});
